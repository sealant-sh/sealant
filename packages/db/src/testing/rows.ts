/** The smallest valid spec whose workspace comes from a git repository or a capture session. */
export const sourceSpec = (kind: "git" | "capture"): NewWorkspace =>
  newWorkspaceSchema.parse({
    sources: {
      workspace:
        kind === "capture"
          ? { kind: "capture", endpoint: "https://mend.example.com/session/s1", worktreeId: "wt_1" }
          : { kind: "git", url: "https://github.com/example/repo.git" },
    },
    harness: { id: "opencode" },
  });

const DEFAULT_SPEC = sourceSpec("git");

